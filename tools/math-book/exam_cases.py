"""Applied assessment cases; canonical banks remain unchanged.

The six versions share learning objectives, not identical fixed questions.
Numeric variants are never counted as additional canonical questions.
"""
from copy import deepcopy
from fractions import Fraction as F


def assessment_cases(ch, rows, v):
    rows = deepcopy(rows)
    n = v + 2
    for q in rows:
        family = int(q['family'].split('-')[-1])

        def case(prompt, answer, options=None, expression=None, feedback=None, kind=None):
            q.update(prompt=prompt, answer=str(answer), options=options or [], aliases=[],
                     mistakes={}, type=kind or q['type'])
            q['check'] = ({'kind': 'number', 'expression': expression} if expression else
                          {'kind': 'reviewed-case', 'review': 'Applied case reviewed with its distractors.'})
            if ch == 1:
                q['verify'] = {'op': 'literal', 'expected': str(answer)}
            if feedback:
                q['feedback'] = feedback
            q['assessmentCase'] = {'version': v, 'canonicalFamily': q['family']}

        def mc(prompt, correct, wrong, feedback=None):
            case(prompt, correct, [str(correct), *map(str, wrong)], feedback=feedback)

        def num(prompt, answer, expr, feedback=None):
            case(prompt, answer, expression=expr, feedback=feedback, kind='short')

        if ch == 1:
            if family == 33:
                mc(f'A={{{n},{n+1},{n+2}}} و B={{{n+1},{n+3}}}؛ کدام فهرست با A−(A∩B) برابر است؟',
                   f'{{{n}, {n+2}}}', [f'{{{n+1}}}', f'{{{n+3}}}', f'{{{n}, {n+1}, {n+2}, {n+3}}}'])
                q['mistakes']={
                    f'{{{n+1}}}':'به‌جای حذف عضوهای مشترک از A، اشتراک را نگه داشته‌ای',
                    f'{{{n+3}}}':'عضو مخصوص B را نوشته‌ای، در حالی که تفاضل خواسته‌شده باید از اعضای A ساخته شود',
                    f'{{{n}, {n+1}, {n+2}, {n+3}}}':'اجتماع را نوشته‌ای، در حالی که عضو مشترک و عضو مخصوص B در تفاضل خواسته‌شده نیستند',
                }
            elif family == 51:
                num('تعداد اعضای A={∅, {'+str(n)+'}, {{'+str(n)+'}}} چند است؟', 3, 'Integer(3)')
            elif family == 53:
                target = v + 2
                mc(f'در پرتاب دو تاس سالم، چرا احتمال مجموع {target} را نمی‌توان با شمردن یازده مجموع، برابر 1/11 گرفت؟',
                   'مجموع‌ها هم‌شانس نیستند', ['همهٔ مجموع‌ها به یک تعداد زوج مرتب ساخته می‌شوند', 'تاس فقط دو وجه دارد', 'ترتیب دو تاس هیچ حالت تازه‌ای نمی‌سازد'],
                   f'برای مجموع {target} باید زوج‌های مرتب مطلوب را از میان سی‌وشش زوج هم‌شانس بشماری؛ خود مجموع‌ها هم‌شانس نیستند.')
                q['mistakes']={
                    q['options'][1]:'تعداد زوج‌های مرتبِ سازندهٔ مجموع‌ها یکسان نیست؛ مثلاً مجموع دو فقط یک زوج دارد',
                    q['options'][2]:'در صورت سؤال هر تاس استاندارد شش وجه دارد، نه دو وجه',
                    q['options'][3]:'در دو تاس قابل تشخیص، جابه‌جایی دو عدد متفاوت یک زوج مرتبِ تازه می‌سازد',
                }
        elif ch == 2:
            if family == 1:
                mc(f'عدد {n}/({n+1}) چرا گویاست؟', 'صورت و مخرج صحیح‌اند و مخرج ناصفر است',
                   ['چون هر عدد مثبت گویاست', 'چون فقط عددهای صحیح گویا هستند', 'چون هر کسر، مخرج صفر هم داشته باشد مجاز است'])
            elif family == 4:
                mc(f'در زنجیرهٔ ℕ⊆ℤ⊆ℚ⊆ℝ، کوچک‌ترین مجموعهٔ شامل −{n} کدام است؟', 'ℤ', ['ℕ', 'ℚ', 'ℝ'])
            elif family == 10:
                case(f'دو عدد حقیقی با حاصل ضرب −{n*n} حتماً هم‌علامت‌اند.', 'نادرست')
            elif family == 25:
                case(f'عدد √{n*n+1} می‌تواند هم‌زمان عضو ℚ و مجموعهٔ گنگ‌ها باشد.', 'نادرست')
            elif family == 30:
                mc(f'اگر a−b=−{n} باشد، |a−b| کدام است؟', str(n), [str(-n), '0', str(n*n)],
                   'ممکن است علامت مقدار داخل قدر مطلق را نگه داشته باشی؛ فاصله از صفر نامنفی است.')
            elif family == 31:
                mc(f'کدام حاصل ضرب، دو عامل گنگ دارد ولی حاصلش {n*n+1} و گویاست؟',
                   f'√{n*n+1}×√{n*n+1}', [f'{n}×{n}', f'√{n*n+1}×{n}', f'{n*n+1}×1'])
            elif family == 33:
                num(f'خطای هر یک از دو اندازه‌گیری حداکثر {F(n,100)} است؛ بیشترین خطای ممکن مجموع چند است؟',
                    F(n,50), f'2*Rational({n},100)')
            elif family == 34:
                case(f'بین دو عدد حقیقی {n}/3 و {n+1}/3 بی‌شمار عدد گویا وجود دارد.', 'درست')
        elif ch == 3:
            if family == 1:
                mc(f'در گزارهٔ «اگر AB=AC={n} باشد، زاویه‌های B و C برابرند»، فرض چیست؟',
                   f'AB=AC={n}', ['برابری زاویه‌های B و C', 'نتیجهٔ مسئله', 'همهٔ زاویه‌ها قائمه‌اند'])
            elif family == 2:
                mc(f'ABCD متوازی‌الاضلاع و AB={n} است؛ می‌خواهیم نشان دهیم CD={n}؛ حکم چیست؟',
                   f'CD={n}', ['متوازی‌الاضلاع بودن', f'AB={n}', 'وجود چهار رأس'])
            elif family == 3:
                case(f'اندازه‌گیری {n+2} مثلث برای اثبات یک گزاره دربارهٔ تمام مثلث‌ها کافی است.', 'نادرست')
            elif family == 9:
                num(f'دو شکل هم‌نهشت‌اند؛ دو ضلع متناظر هر دو {n+3} سانتی‌مترند؛ نسبت این دو طول چند است؟',
                    1, f'Rational({n+3},{n+3})')
            elif family == 10:
                mc(f'ضلع‌های هر یک از دو مثلث {n}، {n+1} و {n+2} است؛ کدام نتیجه معتبر است؟',
                   'دو مثلث هم‌نهشت‌اند', ['هر دو حتماً قائم‌اند', 'هیچ اطلاعاتی از زاویه‌ها نداریم', 'فقط محیط‌ها برابر است و هم‌نهشتی نتیجه نمی‌شود'])
            elif family == 11:
                mc('کدام جفت شکل حتماً متشابه است؟', f'دو مربع با ضلع‌های {n} و {n+2}',
                   [f'دو مستطیل {n}×{n+1} و {n}×{n+2}', f'دو مثلث با ضلع‌های 3،4،5 و {n+2}،{n+3}،{n+4}', f'یک مربع و مستطیل {n}×{n+1}'])
            elif family == 12:
                mc(f'AB=DE={n} و AC=DF={n+2}؛ کدام برابری، معیار ضلع، زاویه، ضلع را کامل می‌کند؟',
                   'زاویهٔ A برابر زاویهٔ D', ['زاویهٔ B برابر زاویهٔ E', 'زاویهٔ C برابر زاویهٔ F', 'فقط زاویهٔ B برابر زاویهٔ F'])
            elif family == 13:
                mc(f'دو زاویهٔ متناظر {40+v} و {60+v} درجه و ضلع بین آن‌ها در دو مثلث {n} است؛ معیار هم‌نهشتی چیست؟',
                   'زاویه، ضلع، زاویه', ['ضلع، ضلع، ضلع', 'فقط برابری سه زاویه', 'فقط برابری محیط'])
            elif family == 14:
                case(f'دو مثلث متساوی‌الاضلاع با ضلع‌های {n} و {n+1} چون سه زاویهٔ برابر دارند، هم‌نهشت‌اند.', 'نادرست')
            elif family == 15:
                mc(f'دو مثلث قائم، وتر {5*n} و یک ضلع قائمهٔ متناظر {3*n} دارند؛ چه نتیجه‌ای معتبر است؟',
                   'دو مثلث هم‌نهشت‌اند', ['فقط وترها برابرند و نتیجه‌ای نداریم', 'فقط محیط‌ها برابر است', 'هر دو متساوی‌الاضلاع‌اند'])
            elif family == 28:
                mc(f'زاویه‌های مثلث {20+v}، {30+v} و {130-2*v} درجه است؛ محل برخورد ارتفاع‌ها کجاست؟',
                   'بیرون مثلث', ['داخل مثلث', 'همیشه وسط یک ضلع', 'روی رأس زاویهٔ قائمه'])
            elif family == 29:
                mc(f'در ABC، زاویهٔ A برابر 30 درجه، BC={5*n} و AC={8*n} است؛ دو ضلع و زاویهٔ غیرمحصور چه وضعی دارند؟',
                   'ممکن است دو مثلث غیرهم‌نهشت این داده‌ها را داشته باشند', ['این داده‌ها همیشه ضلع، زاویه، ضلع‌اند', 'فقط یک مثلث با این داده‌ها ممکن است', 'هیچ مثلثی با این داده‌ها ساخته نمی‌شود'])
            elif family == 33:
                mc(f'از P دو مماس PA و PB بر دایرهٔ مرکز O و شعاع {n} رسم شده؛ کدام برابری پیش از اثبات PA=PB معلوم است؟',
                   f'OA=OB={n}', ['PA=PB را فرض می‌کنیم', f'OP={n}', 'OA=PA بدون دادهٔ دیگر'])
            elif family == 38:
                num(f'زاویه‌های مثلث x، 2x و {v+2}x درجه‌اند؛ x چند است؟', F(180,v+5), f'180/(1+2+{v+2})')
            elif family == 41:
                num(f'در متوازی‌الاضلاع، یک زاویه {v+2} برابر زاویهٔ مجاور است؛ زاویهٔ کوچک‌تر چند درجه است؟',
                    F(180,v+3), f'180/({v+2}+1)')
            elif family == 43:
                mc(f'دو مثلث قائم وتر برابر {5*n} دارند؛ یک ضلع قائمهٔ اول {3*n} است؛ کدام داده هم‌نهشتی را تضمین می‌کند؟',
                   f'ضلع قائمهٔ متناظر در دومی {3*n} باشد', ['فقط هر دو زاویهٔ قائمه دارند', f'فقط یکی از زاویه‌ها کمتر از {40+v} درجه باشد', 'نام رأس‌هایشان یکسان باشد'])
        elif ch == 4:
            if family == 26:
                num(f'اگر 8^x=2^{3*(v+2)} باشد، x چند است؟', v+2, f'{3*(v+2)}/3')
            elif family == 29:
                num(f'حاصل (6×10^(−{v+3}))÷(2×10^2) را c×10^n استاندارد می‌نویسیم؛ n چند است؟',
                    -v-5, f'-{v+3}-2')
            elif family == 35:
                case(f'با a=−{n} و b=−{n+1}، نوشتن √a×√b=√(ab) در دستگاه اعداد حقیقی مجاز است.', 'نادرست')
            elif family == 39:
                num(f'اگر 4^(x+1)=2^{2*(v+3)} باشد، x چند است؟', v+2, f'{2*(v+3)}/2-1')
        elif ch == 5:
            if family == 7:
                mc(f'تساوی (x+{n})²=x²+{2*n}x+{n*n} چرا اتحاد است؟',
                   'برای همهٔ مقدارهای حقیقی x درست است', ['فقط برای x=0 درست است', 'چون هر تساوی اتحاد است', 'فقط برای یک عدد حقیقی درست است'])
            elif family == 36:
                case(f'از a<b، بدون تعیین علامت c، همیشه می‌توان نتیجه گرفت {n}ac<{n}bc.', 'نادرست')
        elif ch == 6:
            if family == 11:
                mc(f'خطی از نقطه‌های ({n},{n+4}) و ({n+1},{n+2}) می‌گذرد؛ علامت شیب چیست؟',
                   'منفی', ['مثبت', 'صفر', 'تعریف نشده'])
            elif family == 12:
                num(f'خط‌های y={n}x+1 و y={n+1}x−2 چند نقطهٔ مشترک دارند؟', 1, 'Integer(1)')
            elif family == 46:
                mc(f'دو معادلهٔ y=2x+{n} و {n}y={2*n}x+{n*n} چه رابطهٔ هندسی دارند؟',
                   'دو خط منطبق‌اند', ['موازی و متمایزند', 'فقط یک نقطهٔ مشترک دارند', 'بر هم عمودند'])
        elif ch == 7:
            if family == 1:
                mc('کدام عبارت نسبت دو چندجمله‌ای است؟', f'(x²+{n})/(x−{n+1})',
                   [f'√x/(x+{n})', f'|x|/(x+{n})', f'{n}^x/(x+1)'])
            elif family == 16:
                mc(f'برای x≠0، ساده‌سازی (x²+{n}x)/x کدام است؟', f'x+{n}',
                   [f'x²+{n}', f'x+{n}x', f'{n+1}x'])
            elif family == 23:
                mc(f'در تقسیم بر x²+{n}، کدام عبارت نمی‌تواند باقی‌ماندهٔ استاندارد باشد؟',
                   f'x²+{n+1}', [f'x+{n}', str(n), '0'])
            elif family == 28:
                mc(f'برای x≠0، حاصل ({n}+1/x)/(1/x) چیست؟', f'{n}x+1',
                   [f'{n}+1', f'{n}/x+1', f'({n}+1)/x'])
        elif ch == 8:
            if family == 6:
                num(f'مساحت قاعدهٔ هرم و منشور هر دو {n*n} و ارتفاع هر دو {n+1} است؛ حجم منشور چند برابر حجم هرم است؟',
                    3, f'({n*n}*{n+1})/({n*n}*{n+1}/3)')
            elif family == 7:
                mc(f'مثلث قائم با ضلع‌های قائمه {n} و {n+1} را حول ضلع {n+1} دوران می‌دهیم؛ جسم حاصل چیست؟',
                   'مخروط', ['کره', 'هرم', 'مکعب'])
            elif family == 8:
                mc(f'نیم‌دایره‌ای با شعاع {n} حول قطر خود دوران کامل می‌کند؛ جسم حاصل چیست؟',
                   'کره', ['نیم‌کره', 'مخروط', 'استوانه'])
            elif family == 11:
                mc(f'گنجایش ظرفی با ابعاد {n}، {n+1} و {n+2} سانتی‌متر با کدام واحد گزارش می‌شود؟',
                   'سانتی‌متر مکعب', ['سانتی‌متر', 'سانتی‌متر مربع', 'درجه'])
            elif family == 30:
                num(f'شعاع مخروط {n} برابر شعاع استوانه و ارتفاع‌ها برابرند؛ حجم مخروط چند برابر حجم استوانه است؟',
                    F(n*n,3), f'{n}**2/3')
            elif family == 43:
                num(f'برش موازی قاعدهٔ هرم، هرم کوچک متشابهی با ارتفاع 1/{n} ارتفاع اصلی می‌سازد؛ حجم کوچک چه کسری از اصلی است؟',
                    F(1,n**3), f'Rational(1,{n})**3')
    return rows
